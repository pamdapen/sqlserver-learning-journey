/* ============================================================
   02 分组聚合：2011-2014 年度销售趋势
   日期：2026-09-13
   要点：GROUP BY 分组 / 聚合函数 / 列别名 AS
   对照：GROUP BY 相当于 Excel 透视表的「行标签」，
         SUM/COUNT/AVG 相当于「值字段」
   ============================================================ */

USE AdventureWorks2022;

SELECT YEAR(OrderDate)  AS 年份,
       COUNT(*)         AS 订单笔数,
       SUM(TotalDue)    AS 销售总额,
       AVG(TotalDue)    AS 平均每单金额
FROM   Sales.SalesOrderHeader
GROUP BY YEAR(OrderDate)
ORDER BY 年份;

/* 结果：
   2011 |  1,607 | 14,155,699.52 | 8,808.77
   2012 |  3,915 | 37,675,700.31 | 9,623.42
   2013 | 14,182 | 48,965,887.96 | 3,452.68
   2014 | 11,761 | 22,419,498.32 | 1,906.26

   业务解读：2013 年订单数暴涨而客单价腰斩，
   说明销售结构从「少量大额批发」转向「大量小额零售」。
   —— 数据不只是算数，要能解释。
*/
